import { createRequire } from 'node:module';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const require = createRequire(import.meta.url);
const { chromium } = require('C:/Users/Ivan/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const out = path.dirname(fileURLToPath(import.meta.url));
const url = process.env.QA_URL || 'http://127.0.0.1:54837';
assert.ok(['127.0.0.1', 'localhost'].includes(new URL(url).hostname));
const browser = await chromium.launch({ headless: true, channel: 'chrome' });
const results = [];
try {
  for (const viewport of [{ width: 1440, height: 1000 }, { width: 375, height: 812 }]) {
    const context = await browser.newContext({ viewport });
    await context.route(request => new URL(request).origin !== new URL(url).origin, route => route.abort('blockedbyclient'));
    await context.route('**/api/**', route => route.fulfill({ json: { ok: true } }));
    await context.addInitScript(() => {
      const journalKey = 'karkas.workspace-tab-transaction.v1:guest';
      window.qaJournalEvents = [];
      const originalSet = Storage.prototype.setItem, originalRemove = Storage.prototype.removeItem;
      Storage.prototype.setItem = function (key, value) {
        if (this === localStorage && key === journalKey) window.qaJournalEvents.push({ kind: 'stage', journal: JSON.parse(value) });
        return originalSet.call(this, key, value);
      };
      Storage.prototype.removeItem = function (key) {
        if (this === localStorage && key === journalKey) window.qaJournalEvents.push({ kind: 'clear', tasks: JSON.parse(localStorage.getItem('life_todo_tasks_v2')), tabs: JSON.parse(localStorage.getItem('life_todo_tabs_v2')), archive: JSON.parse(localStorage.getItem('karkas_deleted_tasks_v2')), profile: JSON.parse(localStorage.getItem('karkas.personal-strategy.v1:guest')) });
        return originalRemove.call(this, key);
      };
      if (localStorage.getItem('qa-tabs-seeded')) return;
      localStorage.setItem('qa-tabs-seeded', '1');
      localStorage.setItem('todo_app_lang', 'uk');
      localStorage.setItem('life_todo_tabs_v2', JSON.stringify([{ id: 'qa-retired', name: 'Стара категорія', color: '#f43f5e' }, { id: 'qa-target', name: 'Нова категорія', color: '#38bdf8' }]));
      const task = { id: 'qa-active', title: 'Активне синтетичне завдання', phase: 'qa-retired', priority: 2, steps: 0, currentStep: 0, done: false, pinned: false, createdAt: 1720000000000, timerMode: 'none', timeSpentSeconds: 0 };
      localStorage.setItem('life_todo_tasks_v2', JSON.stringify([task]));
      localStorage.setItem('karkas_deleted_tasks_v2', JSON.stringify([{ ...task, id: 'qa-archived', title: 'Завершене синтетичне завдання', done: true, startedAt: 1720000001000, completedAt: 1720000005000, deletedAt: 1720000006000, timeSpentSeconds: 120 }]));
      localStorage.setItem('karkas.personal-strategy.v1:guest', JSON.stringify({ version: 1, onboardingStatus: 'new', phase: 'goals', goals: [{ id: 'qa-goal', title: 'Синтетична ціль', motive: 'Перевірка', agreed: false, taskIds: ['qa-active', 'qa-archived'], categoryIds: ['qa-retired', 'qa-target'] }], facts: [], barriers: [], preferences: [], feedback: [], actionHistory: [], processedTurnIds: [], reminders: { enabled: false, times: [], maxPerDay: 2 } }));
    });
    const page = await context.newPage();
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.goto(url);
    await page.locator('#manage-tabs-btn').click();
    const manager = page.locator('#manage-tabs-dialog');
    await manager.waitFor();
    const deleteButton = manager.getByRole('button', { name: 'Видалити вкладку: Стара категорія', exact: true });
    await deleteButton.click();
    const confirm = page.locator('#tab-delete-confirm-dialog');
    await confirm.waitFor();
    await page.keyboard.press('Escape');
    await confirm.waitFor({ state: 'hidden' });
    assert.ok(await manager.isVisible(), 'Escape closes only nested confirmation');
    assert.equal(await page.evaluate(() => JSON.parse(localStorage.getItem('life_todo_tabs_v2')).length), 2, 'Escape preserves both tabs');
    assert.equal(await page.evaluate(() => window.qaJournalEvents.length), 0, 'Cancel creates no tab transaction');
    await deleteButton.click();
    await confirm.getByRole('button', { name: 'ВИДАЛИТИ ВКЛАДКУ', exact: true }).click();
    await page.waitForFunction(() => JSON.parse(localStorage.getItem('life_todo_tabs_v2')).length === 1 && localStorage.getItem('karkas.workspace-tab-transaction.v1:guest') === null);
    await confirm.waitFor({ state: 'hidden' });
    const stored = await page.evaluate(() => ({ tasks: JSON.parse(localStorage.getItem('life_todo_tasks_v2')), tabs: JSON.parse(localStorage.getItem('life_todo_tabs_v2')), archive: JSON.parse(localStorage.getItem('karkas_deleted_tasks_v2')), profile: JSON.parse(localStorage.getItem('karkas.personal-strategy.v1:guest')), events: window.qaJournalEvents }));
    assert.deepEqual(stored.tabs.map(tab => tab.id), ['qa-target']);
    assert.equal(stored.tasks[0].phase, 'qa-target');
    assert.equal(stored.archive[0].phase, 'qa-target');
    assert.equal(stored.archive[0].done, true);
    assert.equal(stored.archive[0].completedAt, 1720000005000);
    assert.equal(stored.archive[0].timeSpentSeconds, 120);
    assert.deepEqual(stored.profile.goals[0].categoryIds, ['qa-target']);
    assert.deepEqual(stored.profile.goals[0].taskIds, ['qa-active', 'qa-archived']);
    assert.deepEqual(stored.events.map(event => event.kind), ['stage', 'clear']);
    const staged = stored.events[0].journal;
    assert.equal(staged.beforeWorkspace.tasks[0].phase, 'qa-retired');
    assert.equal(staged.afterWorkspace.tasks[0].phase, 'qa-target');
    assert.equal(staged.afterWorkspace.deletedTasks[0].phase, 'qa-target');
    assert.deepEqual(staged.afterProfile.goals[0].categoryIds, ['qa-target']);
    const cleared = stored.events[1];
    assert.equal(cleared.tasks[0].phase, 'qa-target', 'Active task saved before journal removal');
    assert.equal(cleared.archive[0].phase, 'qa-target', 'Archived task saved before journal removal');
    assert.deepEqual(cleared.profile.goals[0].categoryIds, ['qa-target'], 'Goal links saved before journal removal');
    await page.reload();
    await page.locator('#task-card-qa-active').waitFor();
    assert.equal(await page.evaluate(() => JSON.parse(localStorage.getItem('life_todo_tasks_v2'))[0].phase), 'qa-target');
    assert.equal(await page.evaluate(() => localStorage.getItem('karkas.workspace-tab-transaction.v1:guest')), null);
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    await page.screenshot({ path: path.join(out, viewport.width > 500 ? 'tabs-desktop.png' : 'tabs-mobile.png'), fullPage: true });
    assert.deepEqual(errors, []);
    results.push({ viewport, passed: true, scenarios: ['Nested Escape preserves tab manager', 'Delete migrates active task + completed archive + goal categoryIds', 'Paired journal staged and removed only after durable slots saved', 'Reload retains migrated categories', 'No browser errors or overflow'] });
    await context.close();
  }
  fs.writeFileSync(path.join(out, 'tabs-results.json'), JSON.stringify({ passed: true, syntheticOnly: true, realAiCalls: 0, results }, null, 2));
  console.log(`PASS ${results.length} targeted tab migration desktop/mobile groups`);
} finally { await browser.close(); }
