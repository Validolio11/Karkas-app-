export const getRandomTabColor = (_existingTabs?: { color?: string }[]): string => {
  // Generate a completely random color across the full color spectrum
  const r = Math.floor(Math.random() * 256);
  const g = Math.floor(Math.random() * 256);
  const b = Math.floor(Math.random() * 256);
  // Ensure the color is visible on dark backgrounds
  const max = Math.max(r, g, b);
  const boost = max < 60 ? 60 - max : 0;
  const toHex = (c: number) => Math.min(255, c + boost).toString(16).padStart(2, '0');
  return `#${toHex(r)}${toHex(g)}${toHex(b)}`;
};

